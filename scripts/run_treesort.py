   def build_input_fasta_from_group(self, group_path: str, out_fasta_path: str):
      """
      Building the input FASTA file from a genome group:
         1) Get genome IDs from the genome group
         2) Fetch metadata for each genome (chunked)
         3) Download FASTA for each genome
         4) Rewrite FASTA headers and validate the FASTA content
         5) Write the FASTA file to out_fasta_path
      """
      msg_prefix = "\t[build_input_fasta_from_group]"

      sys.stdout.write(f"{msg_prefix} Using the genome group at {group_path}\n")

      genome_ids = self.get_genome_ids_from_group(group_path)
      if genome_ids is None or len(genome_ids) < 1:
         raise ValueError("Error building a FASTA file from a genome group: No genome IDs were found")

      # Get metadata for all genome IDs.
      meta = self.fetch_all_metadata(genome_ids)
      if not meta or len(meta) < 1:
         raise RuntimeError("Error building a FASTA file from a genome group: Unable to fetch valid metadata")
      
      valid_genome_count = 0

      # Create and write sequences to the FASTA file. Ignore genomes with invalid metadata.
      with open(out_fasta_path, "w", encoding="utf-8") as fout:
         for genome_id in genome_ids:
            try:
               # Get the genome metadata for this genome ID.
               genome = meta.get(genome_id)
               if not genome:
                  sys.stdout.write(f"Invalid metadata for genome {genome_id}\n")
                  continue

               fasta = self.download_genome_fasta(genome_id)
               if not fasta or len(safe_trim(fasta)) == 0:
                  sys.stderr.write(f"Invalid FASTA for genome {genome_id}\n")
                  continue

               # Reformat the FASTA headers and validate the sequences.
               new_fasta = self.process_genome_fasta(fasta, genome)
               if len(new_fasta) > 0:

                  # Write the FASTA to the file.
                  fout.write(new_fasta)

                  valid_genome_count += 1

            except Exception as e:
               if not e:
                  sys.stderr.write(f"An unknown error occurred processing genome {genome_id}")
               else:
                  sys.stderr.write(f"Error in genome {genome_id}:\n {type(e).__name__}: {e}")

      if valid_genome_count < Constants.MIN_GENOMES_FOR_ANALYSIS:
         raise RuntimeError(f"At least {Constants.MIN_GENOMES_FOR_ANALYSIS} genomes are required for analysis but only {valid_genome_count} were provided")
      
      sys.stdout.write(f"{msg_prefix} Created a FASTA file from the genome group\n")
      sys.stdout.write("\n")
      return


   def _chunked(self, items: List[str], n: int) -> Iterable[List[str]]:
      for i in range(0, len(items), n):
         yield items[i:i+n]


   @staticmethod
   def convert_segments_to_names(segments: list[str]):
      """ Convert numbers, names, or labels like "PB2 (1)" to valid segment names. """
      segment_names = []
      
      for segment in segments:
         segment = safe_trim(segment).upper()
         if len(segment) < 1:
            continue

         # Extract the name from a label with a parenthesized segment number.
         match = re.fullmatch(r"([A-Z][A-Z0-9]*)\s*\([1-8]\)", segment)
         if match:
            segment = match.group(1)

         # Convert numeric segments and validate the resulting name.
         segment_name = Constants.SEGMENT_NUM_TO_NAME.get(segment, segment)
         if segment_name in Constants.VALID_SEGMENTS:
            segment_names.append(segment_name)

      return segment_names


   # Parse the annotated tree file for reassorted strains and create "reassortments.csv".
   def create_reassortments_csv_file(self):

      msg_prefix = "[create_reassortments_csv_file]"

      sys.stdout.write(f"{msg_prefix} About to create the {Constants.REASSORTMENTS_FILE_NAME} file\n")

      # This will be assigned the result of the completed process.
      result = None
      
      # Initialize the list of result rows.
      result_rows = []

      # The paths of the CSV output file and the annotated tree input file.
      csv_file_path = f"{self.work_directory}/{self.job_data.output_file}.csv"
      tree_file_path = f"{self.work_directory}/{self.job_data.output_file}{Constants.TREE_FILE_EXTENSION}"

      # The path of the strain reassortments CSV file we will create.
      reassortments_path = f"{self.work_directory}/{Constants.REASSORTMENTS_FILE_NAME}"

      # Get the path for forester.jar.
      top = safe_trim(os.getenv("KB_TOP"))
      if len(top) < 1:
         raise Exception("Error in create_reassortments_csv_file: Invalid KB_TOP environment variable")
   
      # The path depends on whether TreeSort is run in production or development.
      dev_path = os.path.join(top, "modules", "treesort", "lib", Constants.FORESTER_JAR)
      prod_path = os.path.join(top, "lib", Constants.FORESTER_JAR)

      if os.path.exists(prod_path):
         forester_path = prod_path
      elif os.path.exists(dev_path):
         forester_path = dev_path
      else:
         raise Exception(f"Error in create_reassortments_csv_file: Unable to find {Constants.FORESTER_JAR}")

      cmd = ["java", Constants.FORESTER_JAVA_PARAMETERS, "-cp", forester_path, Constants.FORESTER_TREESORT_REFORMATE_CLASS]

      # Add the path of the annotated tree file.
      cmd.append(tree_file_path)

      # Add the path of the CSV output file.
      cmd.append(csv_file_path)

      # Display the command about to be run.
      sys.stdout.write(f"{msg_prefix} {' '.join(cmd)}\n")

      # Run the command
      result = subprocess.run(cmd, shell=False, check=True)

      if result.returncode != 0 or not os.path.exists(csv_file_path):
         raise RuntimeError(f"Forester was unable to generate the CSV file\n")

      # Write the subprocess' stdout
      sys.stdout.write(f"{msg_prefix} {result.stdout}\n")

      # Open the CSV file
      with open(csv_file_path, newline="", encoding="utf-8") as csvfile:
         reader = csv.reader(csvfile)

         sys.stdout.write(f"{msg_prefix} Reading the results CSV file\n")

         for row in reader:
            
            is_reassorted = False
            is_uncertain = False

            # Get the strain/isolate name.
            strain = safe_trim(row[0])
            if len(strain) < 1:
               continue
            
            # Maintain a distance value for each segment.
            PB2 = ""
            PB1 = ""
            PA = ""
            HA = ""
            NP = ""
            NA = ""
            MP = ""
            NS = ""

            reassortment = ""

            # Look for annotations in columns 1 and 2 (column 0 should have the strain name).
            annotation1 = row[1] if len(row) > 1 else None
            annotation2 = row[2] if len(row) > 2 else None

            # Did this strain have reassortment?
            if annotation1 == "is_reassorted=1":
               # This column should have one or more segment names and distances.
               if not annotation2:
                  continue
               reassortment = annotation2
               is_reassorted = True

            elif annotation2 == "is_reassorted=1":
               # This column should have one or more segment names and distances.
               if not annotation1:
                  continue
               reassortment = annotation1
               is_reassorted = True

            # If reassortment was detected we will determine the affected segment(s).
            if is_reassorted:

               # &rea="NA(124)"
               
               # Update the reassortments count in the results.
               self.results.reassortments += 1

               # Determine which segments were reassorted and get each one's distance.
               for token in reassortment.replace("rea=", "").strip().split(","):

                  if token.startswith("?"):
                     is_uncertain = True
                     token = token[1:]

                  match = re.match(r"([A-Z0-9]+)\((\d+)\)", token)
                  if match:
                     name, number = match.groups()
                     if name == "PB2":
                        PB2 = number
                     elif name == "PB1":
                        PB1 = number
                     elif name == "PA":
                        PA = number
                     elif name == "HA":
                        HA = number
                     elif name == "NP":
                        NP = number
                     elif name == "NA":
                        NA = number
                     elif name == "MP":
                        MP = number
                     elif name == "NS":
                        NS = number
               
            # Update the results
            result_rows.append({
               "strain": strain, 
               "is_reassorted": "Y" if is_reassorted else "",
               "is_uncertain": "Y" if is_uncertain else "",
               "PB2": PB2,
               "PB1": PB1,
               "PA": PA,
               "HA": HA,
               "NP": NP,
               "NA": NA,
               "MP": MP,
               "NS": NS,
            })


      if len(result_rows) > 0:

         sys.stdout.write(f"{msg_prefix} Writing transformed reassortment data to {reassortments_path}\n")

         # Sort the results so that the reassorted strains are at the top.
         sorted_result_rows = sorted(result_rows, key=lambda r: r["is_reassorted"], reverse=True)

         # Create the strain reassortments file.
         with open(reassortments_path, "w+", newline="", encoding="utf-8") as result_file:
            writer = csv.DictWriter(result_file, fieldnames=["strain", "is_reassorted", "is_uncertain", "PB2", "PB1", "PA", "HA", "NP", "NA", "MP", "NS"])
            writer.writeheader()
            writer.writerows(sorted_result_rows)

      else:
         raise RuntimeError("No strains were found in the CSV results file")

      # FUTURE: Should we delete the CSV file created by forester.jar?

      # Add the reassortments count to the list of TreeSort messages in the results object.
      s = "" if self.results.reassortments == 1 else "s"
      self.results.treesort_list.append(f"TreeSort found {self.results.reassortments} reassortment event{s}")

      sys.stdout.write(f"{msg_prefix} The {Constants.REASSORTMENTS_FILE_NAME} file has been created\n")
      sys.stdout.write("\n")
      return
   

