   def process_genome_fasta(self, fasta_text: str, genome: GenomeMetadata) -> str:
      """
      Iterate over every sequence, reformatting header lines as ">STRAIN|SUBTYPE|SEGMENT|YYYY-MM-DD", only
      include sequences for requested segments, and make sure a sequence for the reference segment exists.
      """

      found_segments = set()

      segment_name = None
      skip_sequence = False

      output_fasta = []

      for line in fasta_text.splitlines(keepends=True):

         # Is this is a header line?
         if line.startswith(">"):

            # If a previous sequence has been parsed, add its segment name to the list of encountered segments.
            if len(output_fasta) > 0 and segment_name is not None:
               found_segments.add(segment_name)

            # Example FASTA header in the input: ">1173138.25.con.0006"
            match = re.search(r"\.(\d+)(\s|$)", line[1:])
            if not match:
               sys.stderr.write(f"Invalid FASTA header format for genome {genome.genome_id}: {line}")
               skip_sequence = True
               continue
            
            # Get the segment number from the header
            segment_num_str = match.group(1)

            # Convert to an int to get rid of zero-padding on the left side.
            segment_num = int(segment_num_str)

            # Convert numeric segment to canonical name
            segment_name = Constants.SEGMENT_NUM_TO_NAME.get(str(segment_num)) or ""

            if segment_name not in self.segments_for_analysis:
               skip_sequence = True
               continue

            if segment_name in found_segments:
               sys.stderr.write(f"Duplicate sequence found for segment {segment_name} in genome {genome.genome_id}\n")
               skip_sequence = True
               continue

            # Don't skip the following lines of bases.
            skip_sequence = False
            
            # Replace the FASTA header
            # TODO: Consider limiting the whitespace that's replaced.
            strain = genome.strain.replace(" ", "_")
            output_fasta.append(f">{strain}|{genome.subtype}|{segment_name}|{genome.collection_date}\n")

         elif not skip_sequence:
            # Add a line of sequence data
            if not line.endswith("\n"):
               line += "\n"
            output_fasta.append(line)

      # If a previous sequence has been parsed, add its segment name to the list of encountered segments.
      if len(output_fasta) > 0 and segment_name is not None and segment_name not in found_segments:
         found_segments.add(segment_name)

      # Did we find enough segments?
      if len(found_segments) < 2:
         sys.stderr.write(f"Excluding FASTA for genome {genome.genome_id}: Not enough segments for analysis ({len(found_segments)})")
         return ""

      # Did we find the reference segment?
      if self.job_data.ref_segment not in found_segments:
         sys.stderr.write(f"Excluding FASTA for genome {genome.genome_id}: No sequence found for reference segment ({self.job_data.ref_segment})")
         return ""

      return "".join(output_fasta)
   

   def process_phyloxml_clade(self, m: re.Match):

      # empty_clade = "<clade>"

      clade: str | None = m.group("clade")
      if not clade:
         return "<clade>"
      
      branch = ""
      is_reassorted = False
      is_tsnode = False
      is_uncertain = False
      name = ""
      properties = []
      property = ""
      ts_node_name = ""

      # All reassorted segment inferences found in the clade XML.
      segments = []

      # A comma-delimited list of segment(distance).
      segments_label = ""

      # Get the name element
      name_match = Constants.PHYLOXML_REGEX.NAME.search(clade)
      if not name_match:
         sys.stderr.write(f"Error in process_phyloxml_clade: No name match for {clade}\n")
         return clade
      
      name = name_match.group("name")
      if not name:
         sys.stderr.write(f"Error in process_phyloxml_clade: Name is empty\n")
         return clade

      name = name.strip()

      # Is this a TS_NODE_* node?
      if name.startswith("TS_NODE_"):
         is_tsnode = True

         # Populate the TS_node name
         ts_node_name = str(name)

         # Clear the name
         name = ""

      # Get the branch length
      branch_match = Constants.PHYLOXML_REGEX.BRANCH_LIST.search(clade)
      if not branch_match:
         branch = ""
      else:
         branch = branch_match.group("branch")
         if not branch:
            branch = ""

      # Look for a comment property
      property_match = Constants.PHYLOXML_REGEX.PROPERTY.search(clade)
      if property_match:
         property = property_match.group("value")
         if property and len(property) > 0:

            # Does the comment property contain "is_reassorted=1"?
            reassorted_match = Constants.PHYLOXML_REGEX.REASSORTED.search(property)
            if reassorted_match and reassorted_match.group("reassorted") == "1":
               is_reassorted = True
            
               # Iterate over every segment(distance) expression.
               for sd in Constants.PHYLOXML_REGEX.SEGMENT_AND_DIST.finditer(property):
                  segment, distance = sd.group("segment"), sd.group("distance")
                  if not segment:
                     continue

                  if len(segments) > 0:
                     segments_label += ", "

                  segments_label += f"{segment}({distance})"

                  if segment.startswith("?"):
                     is_uncertain = True

                  segments.append(segment)

      if is_reassorted and len(segments) > 0:
         if is_tsnode:
            # The TS_* node name is replaced by segment(distance) value(s).
            name = segments_label

            segment_list = ",".join(segments)

            # Add an empty segment property.
            properties.append(f"<property ref=\"{Constants.PHYLOXML_PROPERTY_REF.segment}\" datatype=\"xsd:string\" applies_to=\"node\">{segment_list}</property>")
         
         elif len(name) > 0:
            # Preface the name with the segments label.
            name = f"{segments_label}: {name}"

            # Add a property for every segment.
            for segment in segments:
               properties.append(f"<property ref=\"{Constants.PHYLOXML_PROPERTY_REF.segment}\" datatype=\"xsd:string\" applies_to=\"node\">{segment}</property>")
      else:
         # Add an empty segment property
         properties.append(f"<property ref=\"{Constants.PHYLOXML_PROPERTY_REF.segment}\" datatype=\"xsd:string\" applies_to=\"node\"></property>")

      # Add properties for "is_reassorted", "is_uncertain", and "node_id".
      is_reassorted_text = "yes" if is_reassorted else "no"
      is_uncertain_text = "yes" if is_uncertain else "no"

      properties.append(f"<property ref=\"{Constants.PHYLOXML_PROPERTY_REF.isReassorted}\" datatype=\"xsd:string\" applies_to=\"node\">{is_reassorted_text}</property>")
      properties.append(f"<property ref=\"{Constants.PHYLOXML_PROPERTY_REF.isUncertain}\" datatype=\"xsd:string\" applies_to=\"node\">{is_uncertain_text}</property>")
      properties.append(f"<property ref=\"{Constants.PHYLOXML_PROPERTY_REF.nodeID}\" datatype=\"xsd:string\" applies_to=\"node\">{ts_node_name}</property>")

      property_elements = "".join(properties)

      return (
         "<clade>"
         f"<name>{name}</name>"
         f"<branch_length>{branch}</branch_length>"
         f"{property_elements}"
      )


   # Parse the segment-specific output files containing TreeTime's stdout.
   def process_treetime_stdout_files(self) -> bool:

      msg_prefix = "\t[process_treetime_stdout_files]"

      sys.stdout.write(f"{msg_prefix} About to process stdout from TreeTime\n")

      if self.segments_for_analysis is None or len(self.segments_for_analysis) < 1:
         sys.stderr.write("Error in process_treetime_stdout_files: No segments were specified")
         return False

      is_success = True

      # Iterate over all segments
      for segment in self.segments_for_analysis:

         segment = safe_trim(segment)

         output_filename = f"{self.work_directory}/{segment}{Constants.TREETIME_STDOUT_FILE_SUFFIX}"
   
         try:
            # Open the segment-specific output file.
            with open(output_filename, "r", encoding="utf-8") as output_file:

               lines = output_file.readlines()

               # The first line should contain the segment name.
               segment_name = safe_trim(lines[0])
               if segment_name.startswith("SEGMENT: "):
                  segment_name = segment_name.replace("SEGMENT: ", "")

               # Iterate over every line after the first line.
               for line in lines[1:]:

                  # Parse a line from TreeTime-root's stdout.
                  self.parse_treetime_stdout_line(line, segment_name)

         except FileNotFoundError:
            sys.stderr.write(f"Error in process_treetime_stdout_files: Unable to find the file {output_filename}")
            is_success = False
            continue

      sys.stdout.write(f"{msg_prefix} Finished processing TreeTime stdout\n")

      return is_success
   

   # Run prepare_dataset.sh to build alignments and trees and compile a descriptor file.
   def run_prepare_dataset(self):

      # We will calculate how long prepare_dataset takes.
      start_time = datetime.now()
      
      msg_prefix = "[run_prepare_dataset]"

      sys.stdout.write(f"{msg_prefix} About to run prepare_treesort_dataset.sh\n")

      # This will be assigned the result of the completed process.
      result = None

      try:
         cmd = ["prepare_treesort_dataset"]

         # Specify the reference tree inference method.
         # FUTURE: Consider supporting RAxML in addition to FastTree and IQ-Tree. 
         if (self.job_data.ref_tree_inference and self.job_data.ref_tree_inference == TreeInference.FastTree.value):
            cmd.append(ScriptOption.FastTree.value)

         # The segments (optional)
         if len(self.segments_for_analysis) > 0:
            cmd.append(ScriptOption.Segments.value)
            cmd.append(",".join(self.segments_for_analysis))

         # The input FASTA file
         cmd.append(self.input_filename)

         # The reference segment
         refSegment = self.job_data.ref_segment
         if refSegment:
            cmd.append(refSegment)

         # The working directory
         cmd.append(self.work_directory)

         # Display the command about to be run.
         sys.stdout.write(f"{msg_prefix} {' '.join(cmd)}\n")

         # Run the command
         result = subprocess.run(cmd, shell=False, capture_output=True, text=True, check=True)

         if result.returncode != 0:
            raise Exception(result.stderr)

         # Write the subprocess's stdout to the main stdout.
         #sys.stdout.write(f"{result.stdout}\n")

         # Iterate over lines in the result's stdout to 1) look for the segments 
         # that were found, 2) parse TreeTime data by segment, and 3) to echo messages 
         # to stdout.
         for line in result.stdout.strip().splitlines():
            if line.startswith("FOUND_SEGMENTS:"):

               # TODO: If we only find a subset of segments_for_analysis, shouldn't we complain about it?
               
               # TESTING
               #sys.stdout.write(f"\t{line}\n")

               segment_line = safe_trim(line.replace("FOUND_SEGMENTS:", "").strip())
               if len(segment_line) < 1:
                  raise RuntimeError("No segments were found by prepare_treesort_dataset")

               # Use the segments found by TreeTime to populate the list of segments we will include in the analysis.
               self.populate_segments_for_analysis(safe_trim(segment_line).upper())
               
               sys.stdout.write(f"{msg_prefix} The list of segments has been updated to {','.join(self.segments_for_analysis)}\n")
            else:
               # Write the script's stdout to run_treesort.py's stdout.
               sys.stdout.write(f"\t{line}\n")
         
      except subprocess.CalledProcessError as cpe:
         if cpe.stdout is not None:
            sys.stdout.write(f"{msg_prefix} {cpe.stdout}\n")
         raise RuntimeError(f"Error in TreeSortRunner.run_prepare_dataset:\n {cpe.stderr}")
      
      except Exception as e:
         if result is not None:
            sys.stdout.write(f"{msg_prefix} {result.stdout}\n")
         raise RuntimeError(f"Error in TreeSortRunner.run_prepare_dataset:\n {type(e).__name__}: {e}")

      # Print the end time and total duration of prepare_dataset.
      sys.stdout.write(f"{msg_prefix} Finished prepare_dataset at {TreeSortRunner.format_end_datetime_with_duration(datetime.now(), start_time)}\n")
      sys.stdout.write("\n")
      return


   # Run TreeSort in a sub-process.
   def tree_sort(self):

      msg_prefix = "[tree_sort]"

      sys.stdout.write(f"{msg_prefix} About to run TreeSort\n")

      # This will be assigned the result of the completed process.
      result = None
      
      try:
         cmd = ["treesort"]

         # The clades output path
         clades_path = safe_trim(self.job_data.clades_path)
         if len(clades_path) > 0:
            cmd.append(ScriptOption.CladesPath.value)
            cmd.append(clades_path)

         # The descriptor file is in the working directory.
         cmd.append(ScriptOption.DescriptorPath.value)
         cmd.append(f"{self.work_directory}/{Constants.DESCRIPTOR_FILE_NAME}")

         #-----------------------------------------------------------------------------------------------------------------------------
         # The "match on" options are mutually exclusive.
         #-----------------------------------------------------------------------------------------------------------------------------
         if self.job_data.match_type == MatchType.Strain:
            cmd.append(ScriptOption.MatchOnStrain.value)

         elif self.job_data.match_type == MatchType.EPI:
            cmd.append(ScriptOption.MatchOnEPI.value)

         elif self.job_data.match_type == MatchType.RegEx and self.job_data.match_regex:
            cmd.append(ScriptOption.MatchOnRegex.value)
            cmd.append(self.job_data.match_regex)

         # No collapse
         if self.job_data.no_collapse:
            cmd.append(ScriptOption.NoCollapse.value)

         # The name of the output file to create in the work directory. 
         cmd.append(ScriptOption.OutputFilename.value)
         cmd.append(f"{self.work_directory}/{self.job_data.output_file}{Constants.TREE_FILE_EXTENSION}")
         
         # Equal rates
         if self.job_data.equal_rates:
            cmd.append(ScriptOption.EqualRates.value)

         # Deviation
         cmd.append(ScriptOption.Deviation)
         cmd.append(str(self.job_data.deviation))

         # Inference method
         if self.job_data.inference_method:
            cmd.append(ScriptOption.InferenceMethod.value)
            cmd.append(InferenceMethod(self.job_data.inference_method).value) # NOTE: this seems overly-complex

         # P-value
         cmd.append(ScriptOption.PValue)
         cmd.append(str(self.job_data.p_value))

         # Print the treesort command line that will be run.
         sys.stdout.write(f"{msg_prefix} {' '.join(cmd)}\n")

         # Run the command
         result = subprocess.run(cmd, capture_output=True, text=True, check=True)
         if result.returncode != 0:
            raise Exception(result.stderr)

         # Update the results object with TreeSort's stdout and write to stdout.
         self.results.treesort_stdout = result.stdout
         sys.stdout.write(f"{msg_prefix} {result.stdout}\n")
         
      except subprocess.CalledProcessError as cpe:

         # Update the results object with TreeSort's stdout and write to stdout.
         if cpe.stdout is not None:
            self.results.treesort_stdout = cpe.stdout
            sys.stdout.write(f"{msg_prefix} {cpe.stdout}\n")

         raise RuntimeError(f"Error in TreeSortRunner.tree_sort:\n {cpe.stderr}")
           
      except Exception as e:

         # Update the results object with TreeSort's stdout and write to stdout.
         if result is not None and result.stdout is not None:
            self.results.treesort_stdout = result.stdout
            sys.stdout.write(f"{msg_prefix} {result.stdout}\n")

         if e is None:
            raise RuntimeError(f"An unknown error occurred in TreeSortRunner.tree_sort")
         else:
            raise RuntimeError(f"Error in TreeSortRunner.tree_sort:\n {type(e).__name__}: {e}")

      sys.stdout.write(f"{msg_prefix} TreeSort has completed\n")
      sys.stdout.write("\n")
      return


   # Validate the job's input_source.
   @staticmethod
   def validate_input_source(job_data: JobData):

      if job_data.input_source not in [i.value for i in InputSource]:
         raise ValueError("job_data.input_source is not a valid input source") 

      if job_data.input_source == InputSource.FastaFileID.value:

         # Make sure an input_fasta_file_id value was provided.
         if not job_data.input_fasta_file_id:
            raise ValueError("The input FASTA file ID is invalid")
         
         elif job_data.input_fasta_file_id.startswith("ws:"):

            # Remove the "ws:" prefix from the directory name.
            job_data.input_fasta_file_id = job_data.input_fasta_file_id[3:]

      elif job_data.input_source == InputSource.FastaGroupID.value:

         # Make sure an input_fasta_group_id value was provided.
         if not job_data.input_fasta_group_id:
            raise ValueError("The input FASTA group ID is invalid")

      elif job_data.input_source == InputSource.FastaData:

         if job_data.input_fasta_data is None or len(job_data.input_fasta_data) < 1:
            raise ValueError("The input FASTA data is invalid")
         
      else:
         raise ValueError("The input source is invalid")
      
      return
   

