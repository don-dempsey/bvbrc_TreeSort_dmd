   def is_genome_metadata_valid(self, genome: GenomeMetadata) -> bool:
      """ Evaluate the segment information in the genome metadata. """
      if genome is None:
         sys.stderr.write("Invalid genome\n")
         return False

      # Does the genome have the reference segment?
      if not self.job_data.ref_segment in genome.fasta_segments:
         sys.stderr.write(f"Genome {genome.genome_id} doesn't have the reference segment {self.job_data.ref_segment}\n")
         return False

      valid_segments = set()

      for segment in genome.fasta_segments:

         segment = segment.upper()

         # Is this a segment requested by the user that's not already in the valid_segments set?
         if segment in self.segments_for_analysis and not segment in valid_segments:
            valid_segments.add(segment)

      if len(valid_segments) < 2:
         sys.stderr.write(f"Genome {genome.genome_id} doesn't have enough segments for analysis\n")
         return False
      elif not self.job_data.ref_segment in valid_segments:
         sys.stderr.write(f"Genome {genome.genome_id} doesn't contain the reference segment {self.job_data.ref_segment}\n")
         return False
      
      return True
   

